interface PlatformLogoProps {
  platform: string;
  /** 没有品牌图形时回退到平台单字标记。 */
  fallback: string;
}

export default function PlatformLogo({ platform, fallback }: PlatformLogoProps) {
  if (platform === 'antigravity') {
    return <AntigravityLogo />;
  }

  const logo = PLATFORM_LOGOS[platform];
  if (!logo) {
    return <span className={styles.platformLogoFallback}>{fallback}</span>;
  }

  return (
    <svg
      className={styles.platformLogo}
      viewBox={logo.viewBox ?? '0 0 24 24'}
      aria-hidden="true"
      focusable="false"
    >
      {logo.paths.map((path, index) => (
        <path key={index} d={path.d} fill={path.fill ?? 'currentColor'} />
      ))}
    </svg>
  );
}
